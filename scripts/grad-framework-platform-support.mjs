const BEHAVIOR_FIELDS = [
  "aliasing",
  "autograd",
  "class",
  "condition",
  "contiguity",
  "dtypeEffect",
  "failurePolicy",
  "fixtureCaseIds",
  "id",
  "materialization",
  "observationStatus",
  "referenceContract",
  "sourceDefinitions",
  "surface",
  "targetConformance",
  "truth",
];
const AUTOGRAD_DECISIONS = new Map([
  ["constructor-policy", "conditional-constructor-policy"],
  ["detached", "supported-explicit-detached-boundary"],
  ["graph-edge", "supported-eager-graph-edge"],
  ["identity-or-graph-edge", "conditional-identity-or-eager-graph-edge"],
  ["not-applicable", "not-applicable"],
  ["preserved", "supported-preserved-eager-autograd"],
]);
const MATERIALIZATION_DECISIONS = new Map([
  ["always", "always-owning"],
  ["conditional", "conditional-input-contract"],
  ["none", "none-view-or-identity"],
  ["not-applicable", "not-applicable"],
]);
const CANONICAL_ID =
  /^[a-z][a-z0-9]*(?:\.[a-z][a-z0-9-]*)+$/u;

export function buildGradFrameworkPlatformSupportSource(inventory) {
  requireRecord(inventory, "Grad compatibility inventory");
  requireExactKeys(inventory, [
    "behaviors",
    "dtypeResolution",
    "environment",
    "evidenceTier",
    "executionContext",
    "inventoryId",
    "owner",
    "schemaVersion",
  ], "Grad compatibility inventory");
  if (
    inventory.schemaVersion !== 2
    || inventory.inventoryId !== "browsergrad.grad.compatibility.v1"
    || inventory.owner !== "@unlocalhosted/browsergrad-grad"
    || inventory.evidenceTier !== "pyodide-numpy-reference"
  ) {
    throw new TypeError("Grad compatibility inventory identity is not supported");
  }
  requireRecord(inventory.executionContext, "Grad executionContext");
  requireExactKeys(inventory.executionContext, [
    "backendDecision",
    "exportDecision",
    "residency",
    "transformDecision",
  ], "Grad executionContext");
  if (
    inventory.executionContext.backendDecision !== "numpy-reference-only"
    || inventory.executionContext.exportDecision !== "not-applicable-eager"
    || inventory.executionContext.transformDecision !== "not-applicable-eager"
  ) {
    throw new TypeError("Grad executionContext decisions are not supported");
  }
  requireNonEmpty(inventory.executionContext.residency, "executionContext.residency");
  if (!Array.isArray(inventory.behaviors) || inventory.behaviors.length === 0) {
    throw new TypeError("Grad compatibility inventory behaviors must be non-empty");
  }
  const observed = new Set();
  const operations = inventory.behaviors.map((behavior, index) =>
    normalizeBehavior(behavior, index, inventory.executionContext, observed)
  );
  operations.sort((left, right) =>
    left.operationId.localeCompare(right.operationId)
  );
  return `// Generated by scripts/generate-grad-framework-platform-support.mjs.
// Source: architecture/grad-compatibility-inventory.json
// Do not edit by hand.

export const GRAD_FRAMEWORK_PLATFORM_OPERATIONS = ${JSON.stringify(operations, null, 2)} as const;
`;
}

function normalizeBehavior(behavior, index, executionContext, observed) {
  const label = `Grad compatibility behaviors[${index}]`;
  requireRecord(behavior, label);
  requireExactKeys(behavior, BEHAVIOR_FIELDS, label);
  const behaviorId = requireCanonicalId(behavior.id, `${label}.id`);
  if (observed.has(behaviorId)) {
    throw new TypeError(`Grad compatibility behavior is duplicated: ${behaviorId}`);
  }
  observed.add(behaviorId);
  if (
    behavior.observationStatus !== "verified"
    || (
      behavior.targetConformance !== "browsergrad-defined"
      && behavior.targetConformance !== "pytorch-compatible"
    )
  ) {
    throw new TypeError(`${label} is not a verified target contract`);
  }
  for (const field of [
    "surface",
    "class",
    "condition",
    "dtypeEffect",
    "failurePolicy",
    "referenceContract",
    "truth",
  ]) {
    requireNonEmpty(behavior[field], `${label}.${field}`);
  }
  requireNonEmptyStringArray(behavior.sourceDefinitions, `${label}.sourceDefinitions`);
  requireNonEmptyStringArray(behavior.fixtureCaseIds, `${label}.fixtureCaseIds`);
  const autograd = AUTOGRAD_DECISIONS.get(behavior.autograd);
  if (autograd === undefined) {
    throw new TypeError(`${label}.autograd is not registered: ${behavior.autograd}`);
  }
  const materialization = MATERIALIZATION_DECISIONS.get(
    behavior.materialization,
  );
  if (materialization === undefined) {
    throw new TypeError(
      `${label}.materialization is not registered: ${behavior.materialization}`,
    );
  }
  const refused = behavior.dtypeEffect === "none-rejected";
  const cpu = refused
    ? `refused-${behavior.failurePolicy}`
    : behavior.condition === "all-inputs"
      ? `supported-${behavior.referenceContract}`
      : `conditional-${behavior.referenceContract}-${behavior.condition}`;
  return {
    operationId: `browsergrad.${behaviorId}`,
    publicSurface: behavior.surface,
    implementationId: behaviorId,
    semanticState: "verified-eager-contract",
    shapeContract: behavior.condition,
    dtypeContract: behavior.dtypeEffect,
    decisions: {
      cpu,
      closureAutograd: autograd,
      symbolicVjp: executionContext.transformDecision,
      functionalGrad: executionContext.transformDecision,
      vmap: executionContext.transformDecision,
      onnxExport: executionContext.exportDecision,
      tensorPlan: "not-applicable-eager-framework",
      webgpu: `refused-${executionContext.backendDecision}`,
      residency: refused
        ? "not-applicable-refused-before-execution"
        : executionContext.residency,
      materialization,
    },
  };
}

function requireRecord(value, field) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new TypeError(`${field} must be an object`);
  }
}

function requireExactKeys(record, expected, field) {
  const actual = Object.keys(record).sort();
  const normalizedExpected = [...expected].sort();
  if (JSON.stringify(actual) !== JSON.stringify(normalizedExpected)) {
    throw new TypeError(`${field} fields are not registered`);
  }
}

function requireCanonicalId(value, field) {
  requireNonEmpty(value, field);
  if (!CANONICAL_ID.test(value)) {
    throw new TypeError(`${field} is malformed: ${value}`);
  }
  return value;
}

function requireNonEmptyStringArray(value, field) {
  if (!Array.isArray(value) || value.length === 0) {
    throw new TypeError(`${field} must be a non-empty array`);
  }
  for (const entry of value) requireNonEmpty(entry, field);
}

function requireNonEmpty(value, field) {
  if (typeof value !== "string" || value.trim() === "") {
    throw new TypeError(`${field} must be a non-empty string`);
  }
  return value;
}
