const REQUIREMENT_KINDS = new Set([
  "device-feature",
  "external-service",
  "fixture",
  "oracle",
  "policy",
  "runtime-facility",
  "semantic-feature",
  "simulator",
]);
const REQUIREMENT_ID =
  /^(?:[a-z][a-z0-9]*(?:-[a-z0-9]+)*|[a-z][a-z0-9]*(?:\.[a-z][a-z0-9-]*)+)$/u;
const CAPABILITY_ID =
  /^[a-z][a-z0-9]*(?:\.[a-z][a-z0-9-]*)+$/u;
const SEMANTIC_VERSION =
  /^(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)$/u;

export function buildAssignmentRequirementRegistrySource(records) {
  if (!Array.isArray(records)) {
    throw new TypeError("legacyAssignmentRequirements must be an array");
  }
  const normalized = records.map(normalizeRequirement);
  normalized.sort((left, right) =>
    left.requirementId.localeCompare(right.requirementId)
  );
  const duplicate = normalized.find(
    (entry, index) =>
      index > 0
      && entry.requirementId === normalized[index - 1]?.requirementId,
  );
  if (duplicate !== undefined) {
    throw new TypeError(
      `duplicate assignment requirement: ${duplicate.requirementId}`,
    );
  }

  return `// Generated by scripts/generate-assignment-requirement-registry.mjs.
// Source: architecture/platform-vocabulary.json#legacyAssignmentRequirements
// Do not edit by hand.

import {
  createAssignmentRequirementDefinition,
  type AssignmentRequirementDefinition,
  type AssignmentRequirementDefinitionInput,
} from "@unlocalhosted/browsergrad-semantic-core/requirement";

const ASSIGNMENT_REQUIREMENT_DEFINITION_INPUTS = ${JSON.stringify(normalized, null, 2)} as const satisfies readonly AssignmentRequirementDefinitionInput[];

export const ASSIGNMENT_REQUIREMENT_DEFINITIONS: readonly AssignmentRequirementDefinition[] =
  Object.freeze(
    ASSIGNMENT_REQUIREMENT_DEFINITION_INPUTS.map((input) =>
      createAssignmentRequirementDefinition(input)
    ),
  );
`;
}

function normalizeRequirement(record, index) {
  if (record === null || typeof record !== "object" || Array.isArray(record)) {
    throw new TypeError(
      `legacyAssignmentRequirements[${index}] must be an object`,
    );
  }
  const allowedKeys = new Set([
    "requirementId",
    "semanticVersion",
    "kind",
    "owner",
    "lifecycle",
    "meaning",
    "capabilityId",
  ]);
  const unexpected = Object.keys(record).filter((key) => !allowedKeys.has(key));
  if (unexpected.length > 0) {
    throw new TypeError(
      `assignment requirement ${String(record.requirementId)} has unexpected fields: ${unexpected.join(", ")}`,
    );
  }
  for (const field of [
    "requirementId",
    "semanticVersion",
    "kind",
    "owner",
    "lifecycle",
    "meaning",
  ]) {
    if (typeof record[field] !== "string" || record[field].trim() === "") {
      throw new TypeError(
        `legacyAssignmentRequirements[${index}].${field} must be a non-empty string`,
      );
    }
  }
  if (!REQUIREMENT_ID.test(record.requirementId)) {
    throw new TypeError(
      `assignment requirement ID is malformed: ${record.requirementId}`,
    );
  }
  if (!SEMANTIC_VERSION.test(record.semanticVersion)) {
    throw new TypeError(
      `assignment requirement version is malformed: ${record.semanticVersion}`,
    );
  }
  if (!REQUIREMENT_KINDS.has(record.kind)) {
    throw new TypeError(
      `assignment requirement kind is not registered: ${record.kind}`,
    );
  }
  if (record.lifecycle !== "legacy") {
    throw new TypeError(
      `generated assignment requirement must remain legacy: ${record.requirementId}`,
    );
  }
  if (record.capabilityId !== undefined) {
    if (
      record.kind !== "semantic-feature"
      || typeof record.capabilityId !== "string"
      || !CAPABILITY_ID.test(record.capabilityId)
    ) {
      throw new TypeError(
        `assignment requirement capability link is invalid: ${record.requirementId}`,
      );
    }
  }
  return {
    requirementId: record.requirementId,
    semanticVersion: record.semanticVersion,
    kind: record.kind,
    owner: record.owner,
    lifecycle: record.lifecycle,
    meaning: record.meaning,
    ...(record.capabilityId === undefined
      ? {}
      : { capabilityId: record.capabilityId }),
  };
}
