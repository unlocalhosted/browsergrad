const PRESERVATION_LEVELS = new Set([
  "observable-equivalent",
  "portable-relegalized",
  "schedule-preserving",
  "native-facility",
]);
const EXECUTION_TIERS = new Set([
  "semantic-reference",
  "webgpu-core",
  "webgpu-enhanced",
  "native-companion",
  "simulation",
]);
const CANONICAL_ID =
  /^[a-z][a-z0-9]*(?:\.[a-z][a-z0-9-]*)+$/u;
const SEMANTIC_VERSION =
  /^(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)$/u;

export function buildProgramCapabilityRegistrySource(vocabulary) {
  if (
    vocabulary === null
    || typeof vocabulary !== "object"
    || Array.isArray(vocabulary)
  ) {
    throw new TypeError("platform vocabulary must be an object");
  }
  const capabilities = normalizeRecords(
    vocabulary.semanticCapabilities,
    normalizeCapability,
    "semanticCapabilities",
    "capabilityId",
  );
  const backends = normalizeRecords(
    vocabulary.backends,
    normalizeBackend,
    "backends",
    "backendId",
  );
  return `// Generated by scripts/generate-program-capability-registry.mjs.
// Source: architecture/platform-vocabulary.json#semanticCapabilities + #backends
// Do not edit by hand.

import {
  createSemanticBackendDefinition,
  createSemanticCapabilityDefinition,
  type SemanticBackendDefinition,
  type SemanticBackendDefinitionInput,
  type SemanticCapabilityDefinition,
  type SemanticCapabilityDefinitionInput,
} from "@unlocalhosted/browsergrad-semantic-core/capability";

const SEMANTIC_CAPABILITY_DEFINITION_INPUTS = ${JSON.stringify(capabilities, null, 2)} as const satisfies readonly SemanticCapabilityDefinitionInput[];

const SEMANTIC_BACKEND_DEFINITION_INPUTS = ${JSON.stringify(backends, null, 2)} as const satisfies readonly SemanticBackendDefinitionInput[];

export const SEMANTIC_CAPABILITY_DEFINITIONS: readonly SemanticCapabilityDefinition[] =
  Object.freeze(
    SEMANTIC_CAPABILITY_DEFINITION_INPUTS.map((input) =>
      createSemanticCapabilityDefinition(input)
    ),
  );

export const SEMANTIC_BACKEND_DEFINITIONS: readonly SemanticBackendDefinition[] =
  Object.freeze(
    SEMANTIC_BACKEND_DEFINITION_INPUTS.map((input) =>
      createSemanticBackendDefinition(input)
    ),
  );
`;
}

function normalizeRecords(records, normalize, field, idField) {
  if (!Array.isArray(records)) {
    throw new TypeError(`platform vocabulary ${field} must be an array`);
  }
  const normalized = records.map(normalize);
  normalized.sort((left, right) =>
    left[idField].localeCompare(right[idField])
  );
  const duplicate = normalized.find(
    (entry, index) =>
      index > 0 && entry[idField] === normalized[index - 1]?.[idField],
  );
  if (duplicate !== undefined) {
    throw new TypeError(`duplicate platform vocabulary ID: ${duplicate[idField]}`);
  }
  return normalized;
}

function normalizeCapability(record, index) {
  requireRecord(record, `semanticCapabilities[${index}]`);
  requireExactKeys(record, [
    "capabilityId",
    "semanticVersion",
    "operationVersion",
    "preservationLevels",
    "owner",
    "evidence",
  ], `semantic capability ${String(record.capabilityId)}`);
  requireCanonicalId(record.capabilityId, "capabilityId");
  requireSemanticVersion(record.semanticVersion);
  requireNonEmpty(record.operationVersion, "operationVersion");
  requireNonEmpty(record.owner, "owner");
  return {
    capabilityId: record.capabilityId,
    semanticVersion: record.semanticVersion,
    operationVersion: record.operationVersion,
    preservationLevels: normalizeClosedList(
      record.preservationLevels,
      PRESERVATION_LEVELS,
      "preservationLevels",
    ),
    owner: record.owner,
    evidenceIds: normalizeStringList(record.evidence, "evidence"),
  };
}

function normalizeBackend(record, index) {
  requireRecord(record, `backends[${index}]`);
  requireExactKeys(record, [
    "backendId",
    "semanticVersion",
    "owner",
    "executionTiers",
    "evidence",
  ], `backend ${String(record.backendId)}`);
  requireCanonicalId(record.backendId, "backendId");
  requireSemanticVersion(record.semanticVersion);
  requireNonEmpty(record.owner, "owner");
  return {
    backendId: record.backendId,
    semanticVersion: record.semanticVersion,
    owner: record.owner,
    executionTiers: normalizeClosedList(
      record.executionTiers,
      EXECUTION_TIERS,
      "executionTiers",
    ),
    evidenceIds: normalizeStringList(record.evidence, "evidence"),
  };
}

function normalizeClosedList(values, allowed, field) {
  const normalized = normalizeStringList(values, field);
  for (const value of normalized) {
    if (!allowed.has(value)) {
      throw new TypeError(`${field} contains unregistered value: ${value}`);
    }
  }
  return normalized;
}

function normalizeStringList(values, field) {
  if (!Array.isArray(values) || values.length === 0) {
    throw new TypeError(`${field} must be a non-empty array`);
  }
  for (const value of values) requireNonEmpty(value, field);
  return [...new Set(values)].sort();
}

function requireRecord(value, field) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new TypeError(`${field} must be an object`);
  }
}

function requireExactKeys(record, expected, field) {
  const actual = Object.keys(record).sort();
  const sortedExpected = [...expected].sort();
  if (JSON.stringify(actual) !== JSON.stringify(sortedExpected)) {
    throw new TypeError(`${field} fields are not registered`);
  }
}

function requireCanonicalId(value, field) {
  requireNonEmpty(value, field);
  if (!CANONICAL_ID.test(value)) {
    throw new TypeError(`${field} is malformed: ${value}`);
  }
}

function requireSemanticVersion(value) {
  requireNonEmpty(value, "semanticVersion");
  if (!SEMANTIC_VERSION.test(value)) {
    throw new TypeError(`semanticVersion is malformed: ${value}`);
  }
}

function requireNonEmpty(value, field) {
  if (typeof value !== "string" || value.trim() === "") {
    throw new TypeError(`${field} must be a non-empty string`);
  }
}
